// Writes core/watershed_table.hpp: the 128 by 64 world's water supply, which
// core/world.cpp otherwise evaluates at compile time. ARM builds read the
// table instead, because Adafruit's 32-bit ARM compiler for Windows runs out
// of memory on that evaluation. Native builds check the table against the
// formula, so a stale table fails to compile.
//
//   g++ -std=c++17 -DPETRI_WIDE_WORLD=1 -DPETRI_GENERATING_WATERSHED -Icore \
//       tools/gen/watershed_table.cpp core/checkpoint.cpp core/nests.cpp core/hunting.cpp \
//       core/brain.cpp core/brains_world.cpp -o build/gen_watershed
//   build/gen_watershed > core/watershed_table.hpp
#include "../../core/world.cpp"

#include <cstdio>

int main() {
    std::puts("#pragma once\n\n// The 128 by 64 world's water supply by cell, north half then south half.\n"
              "// Generated by tools/gen/watershed_table.cpp: do not edit.\n\n#include <array>\n#include <cstdint>\n\n"
              "namespace petri {\n\n#ifdef PETRI_WIDE_WORLD");
    const auto write = [](const char* name, const auto& table) {
        std::printf("inline constexpr std::array<std::uint8_t, %u> %s{{", unsigned(table.size()), name);
        for (std::size_t i = 0; i < table.size(); ++i) {
            std::printf("%s%u,", i % 32 ? "" : "\n    ", unsigned(table[i]));
        }
        std::puts("\n}};");
    };
    write("watershed_table_north", petri::north_watershed);
    write("watershed_table_south", petri::south_watershed);
    std::puts("#endif\n\n} // namespace petri");
}
